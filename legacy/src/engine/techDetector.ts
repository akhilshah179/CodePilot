export function detectTechnologies(
  manifestPackages: { name: string; version: string; evidence: Evidence }[],
  files: ProjectFile[] = []
): Technology[] {
  const detected: Technology[] = [];
  const foundTechIds = new Set<string>();

  for (const rule of TECH_RULES) {
    const evidenceList: Evidence[] = [];
    let isDirectManifest = false;
    let codeMatches = 0;
    let matchedVersion = 'latest';
    const matchedFiles = new Set<string>();

    // 1. Check Manifests
    if (rule.matchers.packages) {
      for (const pkg of manifestPackages) {
        const pkgNameLower = pkg.name.toLowerCase();
        for (const targetPkg of rule.matchers.packages) {
          if (pkgNameLower === targetPkg.toLowerCase() || pkgNameLower.includes(targetPkg.toLowerCase())) {
            isDirectManifest = true;
            matchedVersion = pkg.version || 'detected';
            evidenceList.push(pkg.evidence);
            matchedFiles.add(pkg.evidence.file);
          }
        }
      }
    }

    // 2. Check File patterns & code keywords
    for (const file of files) {
      // File Pattern check
      if (rule.matchers.filePatterns) {
        for (const pattern of rule.matchers.filePatterns) {
          if (pattern.test(file.path)) {
            matchedFiles.add(file.path);
            evidenceList.push({
              file: file.path,
              snippet: `File path matches pattern '${pattern.source}'`,
              type: 'config',
              description: `Configuration or manifest file for ${rule.name}`,
            });
          }
        }
      }

      // Code content keywords check
      if (file.content && rule.matchers.codeKeywords) {
        const lines = file.content.split('\n');
        for (let idx = 0; idx < lines.length; idx++) {
          const line = lines[idx];
          for (const keyword of rule.matchers.codeKeywords) {
            if (line.includes(keyword)) {
              codeMatches++;
              matchedFiles.add(file.path);
              if (evidenceList.length < 4) {
                evidenceList.push({
                  file: file.path,
                  line: idx + 1,
                  snippet: line.trim().slice(0, 140),
                  type: 'call',
                  description: `Direct usage of '${keyword}' in source code`,
                });
              }
            }
          }
        }
      }
    }

    // Determine Confidence
    if (evidenceList.length > 0) {
      let confidence: ConfidenceLevel = 'POSSIBLE';
      if (isDirectManifest && codeMatches > 0) {
        confidence = 'CONFIRMED';
      } else if (isDirectManifest || codeMatches >= 2) {
        confidence = 'CONFIRMED';
      } else if (codeMatches > 0 || matchedFiles.size > 0) {
        confidence = 'STRONG_INFERENCE';
      }

      if (!foundTechIds.has(rule.id)) {
        foundTechIds.add(rule.id);
        detected.push({
          id: rule.id,
          name: rule.name,
          category: rule.category,
          version: matchedVersion,
          confidence,
          purpose: rule.purpose,
          role: rule.role,
          whyUsed: rule.whyUsed,
          files: Array.from(matchedFiles),
          evidence: evidenceList,
          connections: [],
          color: rule.color,
        });
      }
    }
  }

  // Populate dynamic connections between detected tech
  for (const tech of detected) {
    if (tech.category === 'Frontend Framework') {
      tech.connections = detected.filter(t => t.category === 'Backend Framework').map(t => t.id);
    } else if (tech.category === 'Backend Framework') {
      tech.connections = detected.filter(t => ['Database', 'Cache', 'Message Queue', 'Authentication', 'Cloud Services', 'Payment Services'].includes(t.category)).map(t => t.id);
    } else if (tech.category === 'ORM') {
      tech.connections = detected.filter(t => t.category === 'Database').map(t => t.id);
    }
  }

  return detected;
}
